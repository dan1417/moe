#!/usr/bin/env python3
"""sweep41 plugin: confirm a scored recipe on other samples with the validator's exact verdict.

Queue item:
  {"kind": "plugin", "module": "confirm41", "label": "t1_d36050", "priority": 8.5,
   "runs": [{"competition": "code", "sample": "tag:A", "limit": 3000},
            {"competition": "mix",  "sample": "tag:B", "limit": 2400}]}
For each run the recipe (configs/merge/k41/<label>.json) and that competition's king (kings.json; for "mix"
every king) are scored on the first `limit` sequences of the sample (losses cached), and
src.parity.verdict.duel (paired bootstrap, B=10000, alpha=0.001, the competition's delta) is recorded in
configs/merge/k41/confirm/<label>.json plus a line in 41.md's campaign log.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
DIR = REPO / "configs/merge/k41"
OUT = DIR / "confirm"
DOC = REPO / "41.md"
MARK = "## Results (live; regenerated by scripts/merge/report41.py)"


def run(server, path: Path, raw: dict) -> None:
    from src.parity.sample import load_live_config
    import sweep41

    label = raw["label"]
    recipe = server.pe.resolve_recipe(str(DIR / f"{label}.json"))
    kings = json.loads((DIR / "kings.json").read_text())
    results = []
    for item in raw["runs"]:
        comp, limit = item["competition"], int(item["limit"])
        live = load_live_config(competition=comp)
        sample = server.pe.resolve_sample(item["sample"], live)
        # keep the server's own objects when the sample is one it already holds (shared loss cache anyway)
        if comp == "mix":
            refs = {c: kings[c] for c in ("math", "code", "text")}
        else:
            refs = {comp: kings[comp]}
        ref_losses = {}
        for c, king in refs.items():
            if king not in ref_losses:
                ref_losses[king] = server.losses(sample, server.Recipe.single(king), limit)[0]
        chall = server.losses(sample, recipe, limit)[0]
        n = min(limit, sample.n)
        mask = np.zeros(sample.n, dtype=bool)
        mask[:n] = True
        for c, king in refs.items():
            k = ref_losses[king]
            if comp == "mix":  # re-weighted specialist estimate from the equal-thirds sample
                st = sweep41.group_stats(k[:n], chall[:n], sample.sources[:n])
                counts = {g: int(round(30000 * w)) for g, w in sweep41.MIX[c].items()}
                res = {"competition": c, "sample": sample.sample_id, "kind": "mix-reweighted", "n": n,
                       **sweep41.comp_stats(st, sweep41.MIX[c], counts), "groups": {g: round(s["mu"], 6) for g, s in st.items()}}
            else:
                v = server.duel(np.where(mask, k, np.nan), np.where(mask, chall, np.nan), sample, delta=live.delta_threshold)
                res = {"competition": c, "sample": sample.sample_id, "kind": "validator-verdict", "n": v["n_sequences"],
                       "mu": round(v["mu_hat"], 6), "lcb": round(v["lcb"], 6), "se": v.get("se_iid"),
                       "win_rate": v.get("win_rate"), "delta": live.delta_threshold, "accepted_on_prefix": v["accepted"],
                       "sources": {s: round(x["mu_hat"], 6) for s, x in v["source_scores"].items()}}
                # what the validator's 30k draw would give if these per-source means and variances hold
                d = k[:n] - chall[:n]
                src = sample.sources[:n]
                var30 = sum((live.settings.n * p.proportion / live.settings.n) ** 2 *
                            d[src == p.name].var(ddof=1) / max(int(round(live.settings.n * p.proportion)), 1)
                            for p in live.settings.manifests)
                res["lcb30k"] = round(v["mu_hat"] - sweep41.Z * float(np.sqrt(var30)), 6)
            res["king"] = Path(king).name[:8]
            results.append(res)
            server.log_result(label, res) if hasattr(server, "log_result") else None
            sweep41.log.info("CONFIRM %-24s %-5s %s n=%d mu %+.5f lcb %+.5f%s", label, c, res["kind"], res["n"], res["mu"],
                             res["lcb"], f" lcb30k {res['lcb30k']:+.5f}" if "lcb30k" in res else "")
    OUT.mkdir(exist_ok=True)
    out = OUT / f"{label}.json"
    prev = json.loads(out.read_text()) if out.exists() else {"label": label, "runs": []}
    prev["runs"].extend([{**r, "time": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())} for r in results])
    out.write_text(json.dumps(prev, indent=1) + "\n")
    line = (f"- {time.strftime('%H:%M', time.gmtime())} UTC confirm `{label}`: " +
            "; ".join(f"**{r['competition'].upper()}** {r['n']} seqs of `{r['sample'][-6:]}` mu {r['mu']:+.5f} lcb {r['lcb']:+.5f}"
                      + (f" lcb30k {r['lcb30k']:+.5f}" if "lcb30k" in r else "") for r in results) + "\n")
    text = DOC.read_text()
    if MARK in text:
        head, tail = text.split(MARK, 1)
        DOC.write_text(head.rstrip("\n") + "\n" + line + "\n" + MARK + tail)
    sweep41.git_commit([out, DOC], f"k41 confirm: {label}")
